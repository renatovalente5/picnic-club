// The places Ana lists are translated with the rest of her words (content/i18n/); these are for
// the towns clients write in their reviews, in whichever language they wrote.
const PLACES = {
  pt: { Lisbon: 'Lisboa', London: 'Londres', Zurich: 'Zurique' },
  en: { Lisboa: 'Lisbon', Londres: 'London', Zurique: 'Zurich' },
};

/** A place name in the page's language (Lisbon, and cities reviews come from). */
export function place(ctx, name) {
  return (PLACES[ctx.lang] || {})[name] || name;
}

/** An internal path in the page's language, keeping its query and its #fragment. */
export function localize(ctx, href) {
  if (ctx.lang === 'en' || typeof href !== 'string' || !href.startsWith('/') || href.startsWith('//') || href.startsWith('/assets/')) return href;
  const [, path, rest] = href.match(/^([^?#]*)(.*)$/);
  const translated = ctx.routes[path];
  if (!translated) throw new Error(`No Portuguese page for the link "${href}". Add it to ROUTES in src/templates/i18n.mjs.`);
  return translated + rest;
}

/** A fixed text in the page's language; {name} is filled from vars. A text missing in Portuguese stops the build. */
export function t(ctx, key, vars = {}) {
  const text = STRINGS[ctx.lang][key];
  if (text === undefined) throw new Error(`Missing ${ctx.lang} text "${key}" in src/templates/i18n.mjs.`);
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? vars[name] : m));
}

